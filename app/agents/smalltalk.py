"""挨拶・お礼・別れの言葉だけの発言かどうかの判定（検索を飛ばしてよいかの目安）。

**まだグラフにはつないでいない**（`app/agents/graph.py` は使わない）。判定だけを先に作り、`tests/test_smalltalk.py` で確かめる。
誤って「雑談」と判定すると、資料の質問が検索されずに答えられてしまう（検索漏れ）ので、**誤判定の側に倒さない**:
閉じた一覧（下の `_PHRASES`）に、記号と空白を除いて **全体が一致**したときだけ真にする。部分一致・前方一致・長さの目安は使わない。
一覧に無い言葉、質問の要素（疑問符・話題の語）が少しでも付いた発言、判断に迷うものは、すべて偽（＝いつもどおり検索する）。
"""

import re
import unicodedata

# 末尾に付いてよい記号・空白（「こんにちは！」「ありがとう〜」）。疑問符は含めない（「こんにちは？」は質問の可能性があるので偽）
_TRAILING = re.compile(r"[\s!！。．.~〜ー〰♪♡☆]+$")

# 一覧に無いものは偽。NFKC で全角英数・半角カナをそろえ、英字は小文字にしてから比べる
_PHRASES = frozenset(
    {
        "こんにちは",
        "こんにちわ",
        "こんばんは",
        "こんばんわ",
        "おはよう",
        "おはようございます",
        "はじめまして",
        "初めまして",
        "ありがとう",
        "ありがとうございます",
        "ありがとうございました",
        "どうも",
        "よろしく",
        "よろしくお願いします",
        "よろしくおねがいします",
        "お疲れ様",
        "お疲れ様です",
        "おつかれさま",
        "おつかれさまです",
        "さようなら",
        "さよなら",
        "ばいばい",
        "またね",
        "hello",
        "hi",
        "thanks",
        "thankyou",
        "thank you",
    }
)


def is_smalltalk(text: str) -> bool:
    """挨拶・お礼・別れの言葉だけなら True。それ以外（資料の質問を含む）は、迷うものも含めて False。"""
    normalized = unicodedata.normalize("NFKC", text).strip().lower()
    normalized = _TRAILING.sub("", normalized)
    return normalized in _PHRASES
